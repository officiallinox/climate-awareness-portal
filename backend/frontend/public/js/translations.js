// Function to get translation
function getTranslation(key, language = 'en') {
    // Split the key by dots to navigate the translations object
    const keys = key.split('.');
    let result = translations[language];
    
    // Navigate through the keys
    for (const k of keys) {
        if (result && result[k]) {
            result = result[k];
        } else {
            // If translation not found, return the key
            return key;
        }
    }
    
    return result;
}

// Shorthand function for getTranslation
function t(key, language = 'en') {
    return getTranslation(key, language);
}

// Function to update all text elements with translations
function updatePageLanguage(language = 'en') {
    // Save the language preference
    localStorage.setItem('language', language);
    
    // Get all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    
    // Update each element with the translation
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        element.textContent = t(key, language);
    });
    
    // Update placeholders
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        element.placeholder = t(key, language);
    });
    
    // Update buttons
    const buttons = document.querySelectorAll('button[data-i18n]');
    buttons.forEach(button => {
        const key = button.getAttribute('data-i18n');
        const icon = button.querySelector('i');
        const iconHTML = icon ? icon.outerHTML : '';
        button.innerHTML = iconHTML + ' ' + t(key, language);
    });
    
    // Update document title
    if (document.title.includes('ClimAware Portal')) {
        const pageName = document.title.split(' - ')[1];
        if (pageName) {
            const pageKey = 'nav.' + pageName.toLowerCase();
            const translatedPage = t(pageKey, language);
            if (translatedPage !== pageKey) {
                document.title = 'ClimAware Portal - ' + translatedPage;
            }
        }
    }
    
    // Dispatch an event to notify that language has changed
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { language } }));
}

// Initialize language from localStorage or default to English
function initializeLanguage() {
    const savedLanguage = localStorage.getItem('language') || 'en';
    updatePageLanguage(savedLanguage);
    
    // Update language selector if it exists
    const languageSelector = document.getElementById('languageSelector');
    if (languageSelector) {
        languageSelector.value = savedLanguage;
    }
}

// Export the functions
window.t = t;
window.updatePageLanguage = updatePageLanguage;
window.initializeLanguage = initializeLanguage;